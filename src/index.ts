import { app, BrowserWindow, dialog, ipcMain, nativeImage } from "electron";
import FileHound from "filehound";
import fs from "fs";
import path from "path";

// Supported image extensions mapped to their MIME type (matched case-insensitively)
const IMAGE_MIME_TYPES = new Map<string, string>([
  ["jpg", "image/jpeg"],
  ["jpeg", "image/jpeg"],
  ["jfif", "image/jpeg"],
  ["png", "image/png"],
  ["webp", "image/webp"],
]);

const getExtension = (filepath: string) =>
  path.extname(filepath).slice(1).toLowerCase();

const isImageFile = (filepath: string) =>
  IMAGE_MIME_TYPES.has(getExtension(filepath));

// Stop looking for a preview after this many directory entries so huge trees stay fast
const PREVIEW_SCAN_LIMIT = 5000;

/**
 * Breadth-first search for the first image inside the given folders (or the path itself
 * if it's an image), skipping hidden entries.
 */
const findFirstImage = async (paths: string[]): Promise<string | null> => {
  const queue = [...paths];
  let scanned = 0;

  while (queue.length && scanned < PREVIEW_SCAN_LIMIT) {
    const current = queue.shift();
    try {
      const stat = await fs.promises.stat(current);
      if (stat.isFile()) {
        if (isImageFile(current)) return current;
        continue;
      }

      const entries = await fs.promises.readdir(current, { withFileTypes: true });
      entries.sort((a, b) => a.name.localeCompare(b.name));
      scanned += entries.length;

      const image = entries.find(
        (e) => e.isFile() && !e.name.startsWith(".") && isImageFile(e.name),
      );
      if (image) return path.join(current, image.name);

      entries
        .filter((e) => e.isDirectory() && !e.name.startsWith("."))
        .forEach((e) => queue.push(path.join(current, e.name)));
    } catch {
      // Missing or unreadable folder, keep looking in the others
    }
  }

  return null;
};

const PREVIEW_SIZE = 128;

const createPreview = async (folders: string[]): Promise<string | null> => {
  const image = await findFirstImage(folders);
  if (!image) return null;

  try {
    const thumbnail = await nativeImage.createThumbnailFromPath(image, {
      width: PREVIEW_SIZE,
      height: PREVIEW_SIZE,
    });
    if (!thumbnail.isEmpty()) return thumbnail.toDataURL();
  } catch {
    // Fall through to decoding the full image
  }

  const fullImage = nativeImage.createFromPath(image);
  return fullImage.isEmpty()
    ? null
    : fullImage.resize({ height: PREVIEW_SIZE }).toDataURL();
};
// This allows TypeScript to pick up the magic constants that's auto-generated by Forge's Webpack
// plugin that tells the Electron app where to look for the Webpack-bundled app code (depending on
// whether you're running in development or production).
declare const MAIN_WINDOW_WEBPACK_ENTRY: string;
declare const MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY: string;

declare global {
  interface Window {
    funcs: any;
  }
}

// Handle creating/removing shortcuts on Windows when installing/uninstalling.
if (require("electron-squirrel-startup")) {
  app.quit();
}

const createWindow = (): void => {
  // Create the browser window.
  const mainWindow = new BrowserWindow({
    height: 600,
    width: 800,
    autoHideMenuBar: true,
    backgroundColor: "#0a1929",
    webPreferences: {
      backgroundThrottling: false,
      preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
    },
  });

  // Disable maximized window for now, as it seems that the small window is prefered by users.
  // mainWindow.maximize();

  ipcMain.handle("loadFolder", async () =>
    dialog.showOpenDialog({
      properties: ["openFile", "multiSelections", "openDirectory"],
    }),
  );

  ipcMain.handle("loadImage", (event, filepath) => {
    return new Promise((resolve, reject) => {
      const base64 = fs.readFileSync(filepath).toString("base64");
      const mime = IMAGE_MIME_TYPES.get(getExtension(filepath)) ?? "image/jpeg";
      const src = `data:${mime};base64,${base64}`;
      resolve(src);
    });
  });

  ipcMain.handle("getDirFilesList", (event, arg) => {
    console.log("arg", arg);
    return FileHound.create()
      .ignoreHiddenDirectories()
      .ignoreHiddenFiles()
      .paths(arg)
      .find()
      // FileHound's .ext() is case-sensitive, which skipped files like "photo.JPG"
      .then((files: string[]) => files.filter(isImageFile));
  });

  ipcMain.handle("getFolderPreview", (event, folders: string[]) =>
    createPreview(folders),
  );

  ipcMain.handle("isFullscreen", () => mainWindow.fullScreen);
  ipcMain.handle("setFullscreen", (event, flag: boolean) =>
    mainWindow.setFullScreen(flag),
  );

  // F11 toggles fullscreen from anywhere in the app, like in a browser
  mainWindow.webContents.on("before-input-event", (event, input) => {
    if (input.type === "keyDown" && input.key === "F11") {
      event.preventDefault();
      mainWindow.setFullScreen(!mainWindow.isFullScreen());
    }
  });

  mainWindow.on("enter-full-screen", () => {
    mainWindow.webContents.send("fullscreen-switched", true);
  });
  mainWindow.on("leave-full-screen", () => {
    mainWindow.webContents.send("fullscreen-switched", false);
  });

  // and load the index.html of the app.
  mainWindow.loadURL(MAIN_WINDOW_WEBPACK_ENTRY);

  // Open the DevTools.
  // mainWindow.webContents.openDevTools();
};

// This method will be called when Electron has finished
// initialization and is ready to create browser windows.
// Some APIs can only be used after this event occurs.
app.on("ready", createWindow);

// Quit when all windows are closed, except on macOS. There, it's common
// for applications and their menu bar to stay active until the user quits
// explicitly with Cmd + Q.
app.on("window-all-closed", () => {
  app.quit();
});

app.on("activate", () => {
  // On OS X it's common to re-create a window in the app when the
  // dock icon is clicked and there are no other windows open.
  if (BrowserWindow.getAllWindows().length === 0) {
    createWindow();
  }
});
